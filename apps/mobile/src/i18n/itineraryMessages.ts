export function dayRejection(code: string, copy: Copy) {
  if (code === 'DAY_ALREADY_EXISTS') return copy.occupied;
  if (code === 'DATE_OUTSIDE_TRIP') return copy.outside;
  if (code === 'VALIDATION_ERROR') return copy.invalid;
  if (code === 'NOT_FOUND') return copy.missing;
  if (code === 'FORBIDDEN') return copy.admin;
  return copy.conflict;
}
